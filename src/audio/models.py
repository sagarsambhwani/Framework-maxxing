"""Pydantic Schemas for Audio Processing, VAD Telemetry & Transcription.

Defines strongly-typed data validation models for:
    1. VADMetrics: Speech onset, pause duration, confidence scores.
    2. TranscribeResult: Decoupled speech-to-text response model.
    3. AudioValidationResult: Audio payload verification before inference.
"""

from typing import Optional, Dict, Any
from pydantic import BaseModel, Field


class VADMetrics(BaseModel):
    """Voice Activity Detection metrics and turn-taking telemetry."""

    is_speech: bool = Field(
        default=True,
        description="Whether active human speech was confirmed in the audio segment."
    )
    confidence: float = Field(
        default=1.0,
        ge=0.0,
        le=1.0,
        description="Confidence probability score from the VAD model (0.0 to 1.0)."
    )
    speech_duration_s: float = Field(
        default=0.0,
        ge=0.0,
        description="Estimated duration of active speech in seconds."
    )
    silence_duration_s: float = Field(
        default=0.0,
        ge=0.0,
        description="Trailing silence duration that triggered the end-of-speech cutoff."
    )
    vad_latency_ms: float = Field(
        default=0.0,
        ge=0.0,
        description="Processing latency consumed by the VAD model in milliseconds."
    )


class AudioValidationResult(BaseModel):
    """Validation check result for incoming audio byte payloads."""

    valid: bool = Field(
        ...,
        description="True if audio payload meets format, size, and duration constraints."
    )
    size_bytes: int = Field(
        default=0,
        ge=0,
        description="Byte size of the raw audio payload."
    )
    format: str = Field(
        default="unknown",
        description="Detected audio container format (wav, webm, mp3, ogg)."
    )
    error_message: Optional[str] = Field(
        default=None,
        description="Explanation of rejection if validation fails."
    )


class TranscribeResult(BaseModel):
    """Unified transcription output schema containing text and telemetry."""

    text: str = Field(
        ...,
        description="Transcribed text generated by the STT model."
    )
    duration_s: float = Field(
        ...,
        ge=0.0,
        description="Execution time of the transcription model in seconds."
    )
    model: str = Field(
        default="whisper-large-v3-turbo",
        description="STT model identifier used for transcription."
    )
    vad_metrics: Optional[VADMetrics] = Field(
        default=None,
        description="Optional VAD telemetry associated with this voice turn."
    )
    metadata: Dict[str, Any] = Field(
        default_factory=dict,
        description="Additional debug or observability attributes."
    )
